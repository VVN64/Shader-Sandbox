window.ShaderSandbox = window.ShaderSandbox || {};
(function (NS) {
  'use strict';

  // Shared start of every example: precision + the uniforms the app sends in.
  var HEADER = [
    '// A fragment shader runs main() once for EVERY pixel, all at the same time.',
    '',
    '// Tell phone/WebGL GPUs (GL_ES) how precise decimal numbers should be.',
    '#ifdef GL_ES',
    'precision mediump float;',
    '#endif',
    '',
    '// "uniform" = a value the app sends in; it is the same for every pixel.',
    '// Canvas size in pixels: u_resolution.x = width, u_resolution.y = height.',
    'uniform vec2 u_resolution;',
    '// Mouse position in pixels; (0,0) is the bottom-left corner.',
    'uniform vec2 u_mouse;',
    '// Seconds since the shader started - use it to animate things.',
    'uniform float u_time;',
    ''
  ].join('\n');

  function example(name, title, body) {
    return { name: name, code: '// ' + title + '\n' + HEADER + body.join('\n') };
  }

  NS.examples = [
    example('Hello gradient', 'HELLO GRADIENT - colour each pixel based on where it is on screen.', [
      '',
      'void main() {',
      '    // gl_FragCoord.xy = this pixel\'s position in pixels; dividing maps it to 0.0-1.0.',
      '    vec2 st = gl_FragCoord.xy / u_resolution.xy;',
      '    // Red grows left->right, green grows bottom->top, blue pulses with time.',
      '    vec3 color = vec3(st.x, st.y, abs(sin(u_time)));',
      '    // Output this pixel\'s colour: vec4(red, green, blue, alpha), each 0.0-1.0.',
      '    gl_FragColor = vec4(color, 1.0);',
      '}',
      ''
    ]),

    example('Shaping function plot', 'SHAPING FUNCTION - draw y = f(x) as a green line over a grey ramp.', [
      '// Tip: select y in main(), right-click -> Graph to see its values in the Graph window.',
      '',
      '// #define makes a named constant; the compiler swaps PI for the number.',
      '#define PI 3.14159265359',
      '',
      '// Returns 1.0 on the curve and 0.0 away from it, giving a thin soft line.',
      'float plot(vec2 st, float pct) {',
      '    // smoothstep(a, b, v) fades 0->1 as v goes a->b; subtracting two makes a thin band.',
      '    return smoothstep(pct - 0.02, pct, st.y) -',
      '           smoothstep(pct, pct + 0.02, st.y);',
      '}',
      '',
      'void main() {',
      '    // Map the pixel position to 0.0-1.0 on both axes.',
      '    vec2 st = gl_FragCoord.xy / u_resolution;',
      '',
      '    // The shaping function: an S-curve from x=0.1 to x=0.9. Try pow(st.x, 5.0)!',
      '    float y = smoothstep(0.1, 0.9, st.x);',
      '',
      '    // Use y as brightness: vec3(y) sets red = green = blue = y, which is a grey.',
      '    vec3 color = vec3(y);',
      '    // How close this pixel is to the curve (1.0 on the line, 0.0 away from it).',
      '    float pct = plot(st, y);',
      '    // Blend: keep the grey away from the line, paint green on the line.',
      '    color = (1.0 - pct) * color + pct * vec3(0.0, 1.0, 0.0);',
      '',
      '    gl_FragColor = vec4(color, 1.0);',
      '}',
      ''
    ]),

    example('Mouse circle', 'MOUSE CIRCLE - a pulsing ring that follows the mouse (hover the preview).', [
      '',
      'void main() {',
      '    // Map the pixel position to 0.0-1.0.',
      '    vec2 st = gl_FragCoord.xy / u_resolution.xy;',
      '    // Stretch x by the width/height ratio so circles stay round on wide canvases.',
      '    st.x *= u_resolution.x / u_resolution.y;',
      '    // Put the mouse position in the same units as st.',
      '    vec2 m = u_mouse / u_resolution.xy;',
      '    m.x *= u_resolution.x / u_resolution.y;',
      '',
      '    // Distance from this pixel to the mouse (0.0 right under the cursor).',
      '    float d = distance(st, m);',
      '    // Ring radius wobbles around 0.2 as time passes.',
      '    float radius = 0.2 + 0.05 * sin(u_time * 3.0);',
      '    // 1.0 when d is close to the radius, fading to 0.0 within 0.02 - a thin ring.',
      '    float ring = 1.0 - smoothstep(0.0, 0.02, abs(d - radius));',
      '    // mix(a, b, t) blends colour a (t=0) into colour b (t=1): dark blue -> light blue.',
      '    vec3 color = mix(vec3(0.05, 0.07, 0.12), vec3(0.42, 0.71, 1.0), ring);',
      '    // Add a soft glow: brightest at the cursor, gone by distance 0.6.',
      '    color += 0.15 * vec3(1.0 - smoothstep(0.0, 0.6, d));',
      '',
      '    gl_FragColor = vec4(color, 1.0);',
      '}',
      ''
    ]),

    example('Plasma', 'PLASMA - add a few moving sine waves together and turn the sum into colour.', [
      '',
      'void main() {',
      '    // Centre the coordinates: (0,0) in the middle, about -1.0 to 1.0 on the short side.',
      '    vec2 st = (gl_FragCoord.xy * 2.0 - u_resolution) / min(u_resolution.x, u_resolution.y);',
      '    // Slow time down a little so the motion is calmer.',
      '    float t = u_time * 0.6;',
      '',
      '    // Each sin() below is a wave pattern; adding them makes the plasma.',
      '    // Vertical stripes sliding sideways.',
      '    float v = sin(st.x * 3.0 + t);',
      '    // Horizontal stripes, wider and slower.',
      '    v += sin((st.y * 3.0 + t) * 0.5);',
      '    // Diagonal stripes.',
      '    v += sin((st.x * 2.0 + st.y * 2.0 + t) * 0.7);',
      '    // A centre point that drifts around in a loop over time.',
      '    vec2 c = st + 0.5 * vec2(sin(t / 3.0), cos(t / 2.0));',
      '    // Circular ripples spreading out from that drifting point (dot(c,c) = distance squared).',
      '    v += sin(sqrt(dot(c, c) * 30.0 + 1.0) + t);',
      '    // Shrink the total so it changes more gently.',
      '    v *= 0.5;',
      '',
      '    // Turn the number v into a rainbow: one cosine wave per channel, each shifted (R, G, B).',
      '    vec3 color = 0.5 + 0.5 * cos(6.28318 * (vec3(0.0, 0.33, 0.67) + v));',
      '    gl_FragColor = vec4(color, 1.0);',
      '}',
      ''
    ]),

    example('Grid of shapes', 'GRID OF SHAPES - repeat space into tiles and spin a square in each one.', [
      '',
      '// Returns 1.0 inside a centred square of the given size, 0.0 outside (soft edges).',
      'float box(vec2 st, vec2 size) {',
      '    // Turn the size into the empty margin on each side of the square.',
      '    size = vec2(0.5) - size * 0.5;',
      '    // 1.0 once we are past the left/bottom margin...',
      '    vec2 uv = smoothstep(size, size + 0.01, st);',
      '    // ...times 1.0 while we are before the right/top margin.',
      '    uv *= smoothstep(size, size + 0.01, vec2(1.0) - st);',
      '    // Inside the square only if inside on both x and y.',
      '    return uv.x * uv.y;',
      '}',
      '',
      '// Builds a 2x2 rotation matrix; multiplying a vec2 by it spins that point by angle a.',
      'mat2 rotate2d(float a) {',
      '    return mat2(cos(a), -sin(a), sin(a), cos(a));',
      '}',
      '',
      'void main() {',
      '    // Map to 0.0-1.0, then stretch x so squares are not squashed on wide canvases.',
      '    vec2 st = gl_FragCoord.xy / u_resolution.xy;',
      '    st.x *= u_resolution.x / u_resolution.y;',
      '    // Scale up 5x: coordinates now run 0.0-5.0, which gives room for a 5x5 grid.',
      '    st *= 5.0;',
      '    // floor() keeps the whole-number part: which tile we are in, e.g. (2.0, 3.0).',
      '    vec2 id = floor(st);',
      '    // fract() keeps the part after the dot (0-1 inside the tile); -0.5 centres it.',
      '    st = fract(st) - 0.5;',
      '    // Spin around the tile centre (each tile offset a bit), then shift back to 0-1.',
      '    st = rotate2d(u_time + (id.x + id.y) * 0.4) * st + 0.5;',
      '',
      '    // A white square in every tile.',
      '    vec3 color = vec3(box(st, vec2(0.45)));',
      '    // Tint each tile a different colour based on its tile id.',
      '    color *= 0.5 + 0.5 * cos(vec3(0.0, 2.0, 4.0) + id.x * 0.7 + id.y * 0.3);',
      '    gl_FragColor = vec4(color, 1.0);',
      '}',
      ''
    ])
  ];
})(window.ShaderSandbox);
